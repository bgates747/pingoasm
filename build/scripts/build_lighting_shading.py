#!/usr/bin/env python3
"""Generate or validate and assemble the Pingo lighting/shading fixture."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[2]
APP_ROOT = PROJECT_ROOT / "apps" / "lighting-shading"
PROFILE_PATH = APP_ROOT / "profile.json"
SOURCE_DIR = APP_ROOT / "src"
TARGET_DIR = APP_ROOT / "tgt"
COMMON_HELPER = PROJECT_ROOT / "apps" / "_common" / "vdu_pingo.inc"
SCRIPTS_DIR = PROJECT_ROOT / "build" / "scripts"
ASSEMBLY_FILENAME = "lighting-shading.asm"
OUTPUT_FILENAME = "lighting-shading.bin"
GENERATED_SOURCE_NAMES = (
    "vdu_pingo.inc",
    "textured-cube.inc",
    "flat-cube.inc",
)
GENERATOR = "build/scripts/build_lighting_shading.py"
CANONICAL_PALETTE_SHA256 = (
    "858b708a30584790b8255450819ffdca148a60150a31ba35be3ff8f70f92f130"
)
EZ80_APPLICATION_WINDOW = 0x80000


def project_path(value: str) -> Path:
    path = (PROJECT_ROOT / value).resolve()
    try:
        path.relative_to(PROJECT_ROOT.resolve())
    except ValueError as exc:
        raise ValueError(f"path escapes project root: {value}") from exc
    return path


def _safe_filename(value: object, suffix: str) -> str:
    filename = str(value)
    path = Path(filename)
    if path.name != filename or path.suffix.lower() != suffix:
        raise ValueError(f"unsafe {suffix} filename: {filename!r}")
    return filename


def load_profile(path: Path = PROFILE_PATH) -> dict[str, Any]:
    profile = json.loads(path.read_text(encoding="utf-8"))
    required = {
        "name",
        "model_obj_source",
        "textured_texture_png_source",
        "textured_texture_filename",
        "textured_texture_size",
        "palette_png_source",
        "palette_rgba2_source",
        "palette_texture_filename",
        "palette_texture_size",
    }
    missing = sorted(required - profile.keys())
    if missing:
        raise ValueError("lighting profile is missing: " + ", ".join(missing))
    if profile["name"] != "lighting-shading":
        raise ValueError("lighting profile name must be lighting-shading")
    for key in (
        "model_obj_source",
        "textured_texture_png_source",
        "palette_png_source",
        "palette_rgba2_source",
    ):
        if not project_path(str(profile[key])).is_file():
            raise ValueError(f"missing profile source: {profile[key]}")
    _safe_filename(profile["textured_texture_filename"], ".rgba2")
    _safe_filename(profile["palette_texture_filename"], ".rgba2")
    for key in ("textured_texture_size", "palette_texture_size"):
        size = profile[key]
        if (
            not isinstance(size, list)
            or len(size) != 2
            or not all(isinstance(value, int) and value > 0 for value in size)
        ):
            raise ValueError(f"{key} needs two positive integers")
    if profile["palette_texture_size"] != [8, 8]:
        raise ValueError("flat palette must be exactly 8x8")
    return profile


def generated_banner(source: str) -> str:
    return (
        "; =============================================================================\n"
        "; AUTO-GENERATED FILE - DO NOT EDIT\n"
        f"; Generated by: {GENERATOR}\n"
        f"; Generated from: {source}\n"
        "; Edit the generator or its authoritative inputs instead.\n"
        "; =============================================================================\n\n"
    )


def copy_common_helper(destination: Path) -> None:
    relative = COMMON_HELPER.relative_to(PROJECT_ROOT).as_posix()
    destination.write_text(
        generated_banner(relative)
        + COMMON_HELPER.read_text(encoding="utf-8").rstrip()
        + "\n",
        encoding="utf-8",
    )


def validate_staging_window(executable: Path, textures: list[Path]) -> None:
    largest_texture = max(texture.stat().st_size for texture in textures)
    required = executable.stat().st_size + largest_texture
    if required >= EZ80_APPLICATION_WINDOW:
        raise ValueError(
            f"executable plus largest staged texture requires {required} bytes; "
            f"eZ80 application window is {EZ80_APPLICATION_WINDOW} bytes"
        )


def validate_existing_source(source_dir: Path = SOURCE_DIR) -> list[tuple[int, int]]:
    """Validate tracked flat UV words before the ordinary assembly path."""
    sys.path.insert(0, str(SCRIPTS_DIR))
    from flat_palette import validate_flat_palette_asm

    for filename in (ASSEMBLY_FILENAME, *GENERATED_SOURCE_NAMES):
        if not (source_dir / filename).is_file():
            raise RuntimeError(f"missing fixture source: {source_dir / filename}")
    return validate_flat_palette_asm(source_dir / "flat-cube.inc", "flat_cube")


def create_payload(profile: dict[str, Any], payload: Path) -> tuple[Path, Path]:
    sys.path.insert(0, str(SCRIPTS_DIR))
    from PIL import Image
    from agonImages import img_to_rgba2
    from flat_palette import verify_palette_image

    textured_png = project_path(str(profile["textured_texture_png_source"]))
    textured_size = tuple(int(value) for value in profile["textured_texture_size"])
    textured_target = payload / str(profile["textured_texture_filename"])
    with Image.open(textured_png) as image:
        if image.size != textured_size:
            raise ValueError(
                f"{textured_png.relative_to(PROJECT_ROOT)} is {image.size}, "
                f"profile declares {textured_size}"
            )
        img_to_rgba2(image, textured_target)

    palette_png = project_path(str(profile["palette_png_source"]))
    verify_palette_image(palette_png).close()
    palette_target = payload / str(profile["palette_texture_filename"])
    with Image.open(palette_png) as image:
        img_to_rgba2(image, palette_target)
    palette_digest = hashlib.sha256(palette_target.read_bytes()).hexdigest()
    if palette_digest != CANONICAL_PALETTE_SHA256:
        raise ValueError(f"generated palette has unexpected SHA-256: {palette_digest}")
    palette_source = project_path(str(profile["palette_rgba2_source"]))
    if palette_target.read_bytes() != palette_source.read_bytes():
        raise ValueError(
            f"canonical palette asset is stale: {palette_source.relative_to(PROJECT_ROOT)}"
        )
    return textured_target, palette_target


def regenerate_source(
    profile: dict[str, Any],
    destination: Path,
    textured_target: Path,
    palette_target: Path,
) -> None:
    sys.path.insert(0, str(SCRIPTS_DIR))
    from blender_obj_to_asm import parse_obj_file, write_data
    from flat_palette import convert_obj_model_data, validate_flat_palette_asm

    copy_common_helper(destination / "vdu_pingo.inc")
    model_source = project_path(str(profile["model_obj_source"]))
    textured_png = project_path(str(profile["textured_texture_png_source"]))
    textured_size = tuple(int(value) for value in profile["textured_texture_size"])
    write_data(
        model_source.stem,
        *parse_obj_file(model_source),
        destination / "textured-cube.inc",
        textured_target,
        textured_size,
        symbol_prefix="textured_cube",
        authoritative_input=model_source.relative_to(PROJECT_ROOT).as_posix(),
    )

    palette_png = project_path(str(profile["palette_png_source"]))
    flat_data, selections = convert_obj_model_data(model_source, textured_png)
    write_data(
        model_source.stem,
        *flat_data,
        destination / "flat-cube.inc",
        palette_target,
        tuple(int(value) for value in profile["palette_texture_size"]),
        symbol_prefix="flat_cube",
        authoritative_input=(
            f"{model_source.relative_to(PROJECT_ROOT).as_posix()}; "
            f"{textured_png.relative_to(PROJECT_ROOT).as_posix()}; "
            f"{palette_png.relative_to(PROJECT_ROOT).as_posix()}"
        ),
    )
    validate_flat_palette_asm(destination / "flat-cube.inc", "flat_cube")
    expected_cube_selections = [25, 12, 9, 16, 17, 10] * 2
    if selections != expected_cube_selections:
        raise ValueError(
            "Cube predominant palette selection changed: "
            + ",".join(str(value) for value in selections)
        )


def build(*, regenerate: bool = False) -> Path:
    profile = load_profile()
    if not (SOURCE_DIR / ASSEMBLY_FILENAME).is_file():
        raise RuntimeError(f"missing fixture source: {SOURCE_DIR / ASSEMBLY_FILENAME}")
    if not regenerate:
        validate_existing_source(SOURCE_DIR)

    temporary_root = Path(tempfile.mkdtemp(prefix=".lighting-build-", dir=APP_ROOT))
    staged_source = temporary_root / "src"
    payload = temporary_root / "tgt"
    staged_source.mkdir()
    payload.mkdir()
    try:
        shutil.copy2(SOURCE_DIR / ASSEMBLY_FILENAME, staged_source / ASSEMBLY_FILENAME)
        textured_target, palette_target = create_payload(profile, payload)
        if regenerate:
            regenerate_source(profile, staged_source, textured_target, palette_target)
        else:
            for filename in GENERATED_SOURCE_NAMES:
                shutil.copy2(SOURCE_DIR / filename, staged_source / filename)

        output = payload / OUTPUT_FILENAME
        output_argument = os.path.relpath(output.resolve(), staged_source.resolve())
        subprocess.run(
            ["ez80asm", ASSEMBLY_FILENAME, output_argument],
            cwd=staged_source,
            check=True,
        )
        validate_staging_window(output, [textured_target, palette_target])

        if regenerate:
            for filename in GENERATED_SOURCE_NAMES:
                (staged_source / filename).replace(SOURCE_DIR / filename)

        previous_target = temporary_root / "previous-tgt"
        if TARGET_DIR.exists():
            TARGET_DIR.rename(previous_target)
        try:
            payload.rename(TARGET_DIR)
        except BaseException:
            if previous_target.exists():
                previous_target.rename(TARGET_DIR)
            raise
        if previous_target.exists():
            shutil.rmtree(previous_target)
        return TARGET_DIR / OUTPUT_FILENAME
    finally:
        if temporary_root.exists():
            shutil.rmtree(temporary_root)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--regenerate",
        action="store_true",
        help="explicitly regenerate tracked helper/model includes before assembly",
    )
    args = parser.parse_args()
    output = build(regenerate=args.regenerate)
    print(f"Built {output.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
