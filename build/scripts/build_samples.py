#!/usr/bin/env python3
"""Build the Pingo assembly applications into their local tgt directories."""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[2]
APPS_ROOT = PROJECT_ROOT / "apps"
COMMON_ROOT = APPS_ROOT / "_common"
MODELS_ROOT = PROJECT_ROOT / "src/asm/models"
GENERATOR = "build/scripts/build_samples.py"

GENERATED_APPS = {
    "movecam": "cam",
    "moveobj": "obj",
}

SPECIALIZED_APPS = {
    "moveair": "jet.asm",
    "movefsim": "fsim.asm",
    "wolf": "wolf.asm",
}

# Hand-developed sources that the build must preserve. Their target payload is
# recreated from explicit tracked runtime assets before assembly.
STATIC_APPS = {
    "moveobj-local": (
        "jet.asm",
        ("jet.rgba2",),
    ),
    "moveair-local": (
        "jet.asm",
        ("jet.rgba2",),
    ),
}

INCLUDE_RE = re.compile(r'include\s+"([^"]+)"')
TEXTURE_RE = re.compile(r'_texture:\s*db\s+"([^"]+)"')


def generated_banner(source: Path) -> str:
    source_name = source.relative_to(PROJECT_ROOT).as_posix()
    return (
        "; =============================================================================\n"
        "; AUTO-GENERATED FILE - DO NOT EDIT\n"
        f"; Generated by: {GENERATOR}\n"
        f"; Generated from: {source_name}\n"
        "; Edit the generator or its authoritative inputs instead.\n"
        "; =============================================================================\n\n"
    )


def normalized_assembly(text: str) -> str:
    return "\n".join(line.rstrip() for line in text.splitlines()) + "\n"


def write_generated_copy(source: Path, destination: Path) -> None:
    destination.write_text(
        generated_banner(source)
        + normalized_assembly(source.read_text(encoding="utf-8")),
        encoding="utf-8",
    )


def block_range(lines: list[str], name: str) -> range:
    start_marker = f"; {name}"
    end_marker = f"; end {name}"
    start = None

    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped == start_marker:
            start = index + 1
        elif stripped == end_marker and start is not None:
            return range(start, index)

    raise RuntimeError(f"Missing {name!r} block in model viewer source")


def include_name(line: str) -> str:
    match = INCLUDE_RE.search(line)
    if match is None:
        raise RuntimeError(f"Expected assembly include line, got: {line.rstrip()}")
    return match.group(1)


def select_include(line: str) -> str:
    return f'    include "{include_name(line)}"\n'


def assemble(source_dir: Path, asm_filename: str, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.unlink(missing_ok=True)
    output_argument = os.path.relpath(output.resolve(), source_dir.resolve())
    subprocess.run(
        ["ez80asm", asm_filename, output_argument],
        cwd=source_dir,
        check=True,
    )


def generate_app(app_name: str, input_type: str) -> list[Path]:
    app_root = APPS_ROOT / app_name
    source_dir = app_root / "src"
    target_dir = app_root / "tgt"

    if source_dir.exists():
        shutil.rmtree(source_dir)
    if target_dir.exists():
        shutil.rmtree(target_dir)
    source_dir.mkdir(parents=True)
    target_dir.mkdir()

    app_source = COMMON_ROOT / "model_viewer.asm"
    lines = app_source.read_text(encoding="utf-8").splitlines(keepends=True)

    for index in block_range(lines, "application includes"):
        filename = include_name(lines[index])
        write_generated_copy(COMMON_ROOT / filename, source_dir / filename)

    input_filename = f"input{input_type}.inc"
    write_generated_copy(
        COMMON_ROOT / input_filename,
        source_dir / input_filename,
    )

    selected_control = False
    for index in block_range(lines, "control includes"):
        if include_name(lines[index]) == input_filename:
            lines[index] = select_include(lines[index])
            selected_control = True
            break
    if not selected_control:
        raise RuntimeError(f"No control include for input type {input_type!r}")

    outputs: list[Path] = []
    for index in block_range(lines, "model includes"):
        model_filename = include_name(lines[index])
        model_source = MODELS_ROOT / model_filename
        model_destination = source_dir / model_filename
        write_generated_copy(model_source, model_destination)

        model_text = model_source.read_text(encoding="utf-8")
        for texture_filename in TEXTURE_RE.findall(model_text):
            shutil.copy2(
                MODELS_ROOT / texture_filename,
                target_dir / texture_filename,
            )

        generated_lines = lines.copy()
        generated_lines[index] = select_include(generated_lines[index])
        asm_filename = f"{Path(model_filename).stem}.asm"
        asm_path = source_dir / asm_filename
        asm_path.write_text(
            generated_banner(app_source)
            + normalized_assembly("".join(generated_lines)),
            encoding="utf-8",
        )

        binary_path = target_dir / f"{Path(model_filename).stem}.bin"
        assemble(source_dir, asm_filename, binary_path)
        outputs.append(binary_path)

    return outputs


def build_specialized_app(app_name: str, asm_filename: str) -> Path:
    source_dir = APPS_ROOT / app_name / "src"
    target_dir = APPS_ROOT / app_name / "tgt"
    if not source_dir.is_dir():
        raise RuntimeError(f"Missing application source directory: {source_dir}")
    binary_path = target_dir / f"{Path(asm_filename).stem}.bin"
    assemble(source_dir, asm_filename, binary_path)
    return binary_path


def build_static_app(
    app_name: str,
    asm_filename: str,
    runtime_assets: tuple[str, ...],
) -> Path:
    """Rebuild a hand-developed app's target without modifying its source."""
    app_root = APPS_ROOT / app_name
    source_dir = app_root / "src"
    target_dir = app_root / "tgt"
    if not source_dir.is_dir():
        raise RuntimeError(f"Missing application source directory: {source_dir}")

    if target_dir.exists():
        shutil.rmtree(target_dir)
    target_dir.mkdir()

    for asset_filename in runtime_assets:
        shutil.copy2(
            MODELS_ROOT / asset_filename,
            target_dir / asset_filename,
        )

    binary_path = target_dir / f"{Path(asm_filename).stem}.bin"
    assemble(source_dir, asm_filename, binary_path)
    return binary_path


def build_earth_party_app() -> Path:
    """Run the source-preserving generated-asset Earth Party build."""
    from build_earth_party_local import build

    return build()


def build_lighting_shading_app() -> Path:
    """Run the source-validating lighting/shading fixture build."""
    from build_lighting_shading import build

    return build()


def main() -> None:
    outputs: list[Path] = []

    for app_name, input_type in GENERATED_APPS.items():
        outputs.extend(generate_app(app_name, input_type))

    for app_name, asm_filename in SPECIALIZED_APPS.items():
        outputs.append(build_specialized_app(app_name, asm_filename))

    for app_name, (asm_filename, runtime_assets) in STATIC_APPS.items():
        outputs.append(
            build_static_app(
                app_name,
                asm_filename,
                runtime_assets,
            )
        )

    outputs.append(build_earth_party_app())
    outputs.append(build_lighting_shading_app())

    print(f"Built {len(outputs)} binaries:")
    for output in outputs:
        print(f"  {output.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
