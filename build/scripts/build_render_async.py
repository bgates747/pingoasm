#!/usr/bin/env python3
"""Generate and assemble the asynchronous Pingo render-completion fixture."""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PROFILE = (
    PROJECT_ROOT / "benchmarks" / "render-async" / "profiles" / "cube.json"
)
GENERATOR = "build/scripts/build_render_async.py"
VDU_HELPERS = PROJECT_ROOT / "benchmarks" / "_common" / "vdu_pingo.inc"


def banner(source: str) -> str:
    return (
        "; =============================================================================\n"
        "; AUTO-GENERATED FILE - DO NOT EDIT\n"
        f"; Generated by: {GENERATOR}\n"
        f"; Generated from: {source}\n"
        "; Edit the generator or its authoritative inputs instead.\n"
        "; =============================================================================\n\n"
    )


def angle_word(degrees: int) -> int:
    return round((degrees % 360) * 32767 / 360)


def generated_copy(source: Path, destination: Path, profile_source: str) -> None:
    source_rel = source.relative_to(PROJECT_ROOT).as_posix()
    destination.write_text(
        banner(f"{source_rel}; selected by {profile_source}")
        + source.read_text(encoding="utf-8").rstrip()
        + "\n",
        encoding="utf-8",
    )


def assembly(profile: dict[str, object], profile_source: str) -> str:
    width, height = profile["resolution"]
    camera_x, camera_y, camera_z = profile["camera_pose"]
    simulation_steps = int(profile["simulation_steps"])
    simulation_step_ticks = int(profile["simulation_step_ticks"])
    step = int(profile["rotation_step_degrees"])
    rotation_step_angle = angle_word(step)

    return banner(profile_source) + f"""\
mos_load: equ 01h
mos_sysvars: equ 08h
mos_setkbvector: equ 1Dh
sysvar_time: equ 00h
sysvar_gp: equ 037h

    MACRO MOSCALL function
        ld a,function
        rst.lil 08h
    ENDMACRO

    .assume adl=1
    .org 040000h
    jp start

    .align 64
    .db "MOS",0,1

start:
    push af
    push bc
    push de
    push ix
    push iy
    call main
    pop iy
    pop ix
    pop de
    pop bc
    pop af
    ld hl,0
    ret

    include "vdu_pingo.inc"
    include "model.inc"

sid: equ {profile["control_id"]}
mid: equ 1
oid: equ 1
objbmid: equ {profile["texture_bitmap_id"]}
tgtbmid: equ {profile["target_bitmap_id"]}
obj_scale: equ {profile["object_scale"]}
texture_width: equ {profile["texture_width"]}
texture_height: equ {profile["texture_height"]}
texture_size: equ {profile["texture_size"]}
texture_name: db "{profile["texture_filename"]}",0

render_notify_token: equ 0C35Ah
setup_barrier_value: equ 0A5h
render_timeout_ticks: equ 200
simulation_steps: equ {simulation_steps}
simulation_step_ticks: equ {simulation_step_ticks}
rotation_step_angle: equ {rotation_step_angle}

main:
    ld bc,texture_width
    ld de,texture_height
    ld hl,objbmid
    ld ix,texture_size
    ld iy,texture_name
    ld a,1
    call vdu_load_img

    CTB2 tgtbmid,{width},{height}
    CCS sid,{width},{height}
    SV sid,mid,model_vertices,model_vertices_n
    SMVI sid,mid,model_vertex_indices,model_indices_n
    STC sid,mid,model_uvs,model_uvs_n
    STCI sid,mid,model_uv_indices,model_indices_n
    CO sid,oid,mid,objbmid
    SO sid,oid,obj_scale,obj_scale,obj_scale

    xor a
    call vdu_set_scaling
    call cursor_off
    call vdu_clg
    call vdu_flip
    call vdu_clg

    ld hl,oid
    ld bc,0
    ld de,0
    ld iy,0
    call sodabs

    ld bc,{camera_x}
    ld de,{camera_y}
    ld iy,{camera_z}
    call scdabs

    MOSCALL mos_sysvars
    ld (sysvars_pointer),ix
    ; All initialization above is asynchronous. Wait until VDP has consumed
    ; it before timing the first render, or setup latency becomes a false
    ; render timeout on hardware.
    call wait_for_setup_barrier
    ld ix,(sysvars_pointer)
    ld hl,(ix+sysvar_time)
    ld (world_step_time),hl
    xor a
    ld (world_step),a
    ld (world_revision),a
    ld (simulation_done),a
    ld (render_count),a
    ld (result_code),a
    ld (abort_requested),a
    ld (completion_ready),a
    ld (render_in_flight),a
    ld (sequence_initialized),a
    ld hl,0
    ld (world_angle),hl
    ld a,0FFh
    ld (submitted_revision),a

    ld hl,render_packet_callback
    ld c,0
    MOSCALL mos_setkbvector
    call enable_render_notifications
    ei
    call submit_current_render

@game_loop:
    call update_world_state
    call check_render_timeout
    ld a,(completion_ready)
    or a
    call nz,consume_render_completion

    ld a,(render_in_flight)
    or a
    jr nz,@game_loop

    ld a,(result_code)
    or a
    jr nz,@finished

    ld a,(abort_requested)
    or a
    jr nz,@aborted

    ld a,(submitted_revision)
    ld hl,world_revision
    cp (hl)
    jr nz,@submit

    ld a,(simulation_done)
    or a
    jr nz,@finished
    jr @game_loop

@submit:
    call submit_current_render
    jr @game_loop

@aborted:
    ld a,3
    ld (result_code),a
    jr @finished

@finished:
    ; No completion-producing render remains in flight. Disable the producer
    ; before clearing MOS's callback pointer.
    call disable_render_notifications
    ld hl,0
    ld c,0
    MOSCALL mos_setkbvector

    ; Leave the final rendered framebuffer and current video mode intact so
    ; the hardware result remains visible after this diagnostic exits.
    call cursor_on

    ld a,(result_code)
    or a
    ld hl,pass_message
    jr z,@print_result
    cp 1
    ld hl,timeout_message
    jr z,@print_result
    cp 2
    ld hl,rejected_message
    jr z,@print_result
    ld hl,aborted_message
@print_result:
    call printString
    ret

wait_for_setup_barrier:
    ld ix,(sysvars_pointer)
    xor a
    ld (ix+sysvar_gp),a
    ld hl,@command
    ld bc,@end-@command
    rst.lil 18h
@wait:
    ld ix,(sysvars_pointer)
    ld a,(ix+sysvar_gp)
    cp setup_barrier_value
    jr nz,@wait
    ret
@command:
    db 23,0,080h,setup_barrier_value
@end:

; The foreground loop updates world time continuously while VDP renders.
update_world_state:
    ld a,(simulation_done)
    or a
    ret nz
    ld ix,(sysvars_pointer)
    ld a,(ix+sysvar_time)
    ld hl,world_step_time
    sub (hl)
    cp simulation_step_ticks
    ret c

    ; Advance from the prior deadline rather than snapping to "now", so a
    ; temporarily delayed foreground catches up without losing simulation
    ; steps.
    ld a,(hl)
    add a,simulation_step_ticks
    ld (hl),a
    ld hl,(world_updates)
    inc hl
    ld (world_updates),hl

    ld a,(world_step)
    inc a
    ld (world_step),a
    cp simulation_steps
    jr z,@complete_revolution

    ld hl,(world_angle)
    ld de,rotation_step_angle
    add hl,de
    ld (world_angle),hl
    jr @publish

@complete_revolution:
    ld hl,0
    ld (world_angle),hl
    ld a,1
    ld (simulation_done),a

@publish:
    ld a,(world_revision)
    inc a
    ld (world_revision),a
    ret

check_render_timeout:
    ld a,(result_code)
    or a
    ret nz
    ld a,(render_in_flight)
    or a
    ret z
    ld ix,(sysvars_pointer)
    ld a,(ix+sysvar_time)
    ld hl,render_started
    sub (hl)
    cp render_timeout_ticks
    ret c
    ld a,1
    ld (result_code),a
    ret

submit_current_render:
    xor a
    ld (completion_ready),a

    ld de,(world_angle)
    ld hl,oid
    ld bc,0
    ld iy,0
    call sorabs

    ld hl,tgtbmid
    ld (expected_bitmap),hl

    ; Publish all state before the render bytes can reach the VDP. This keeps
    ; the invariant true even in a very fast emulator.
    ld a,(world_revision)
    ld (submitted_revision),a
    ld ix,(sysvars_pointer)
    ld a,(ix+sysvar_time)
    ld (render_started),a
    ld a,1
    ld (render_in_flight),a
    call render_expected_bitmap
    ret

consume_render_completion:
    di
    ld hl,completion_record
    ld de,completion_snapshot
    ld bc,10
    ldir
    xor a
    ld (completion_ready),a
    ei

    ld a,(completion_snapshot+4)
    cp 1
    jp nz,@reject
    ld a,(completion_snapshot+5)
    cp 1
    jp nz,@reject
    ld a,(completion_snapshot+6)
    cp render_notify_token & 0FFh
    jp nz,@reject
    ld a,(completion_snapshot+7)
    cp render_notify_token >> 8
    jp nz,@reject
    ld a,(sequence_initialized)
    or a
    jr z,@accept_first_sequence
    ld hl,completion_snapshot+8
    ld iy,expected_sequence
    ld a,(hl)
    cp (iy+0)
    jp nz,@reject
    inc hl
    ld a,(hl)
    cp (iy+1)
    jp nz,@reject
    jr @sequence_valid

@accept_first_sequence:
    ld hl,completion_snapshot+8
    ld iy,expected_sequence
    ld a,(hl)
    ld (iy+0),a
    inc hl
    ld a,(hl)
    ld (iy+1),a
    ld a,1
    ld (sequence_initialized),a

@sequence_valid:
    call increment_expected_sequence
    di
    xor a
    ld (render_in_flight),a
    ei
    call display_expected_bitmap
    ld a,(render_count)
    inc a
    ld (render_count),a
    ret

@reject:
    ld a,2
    ld (result_code),a
    ret

increment_expected_sequence:
    ld hl,expected_sequence
    inc (hl)
    ret nz
    inc hl
    inc (hl)
    ret

render_expected_bitmap:
    ld hl,(expected_bitmap)
    ld a,l
    ld (@bmid),a
    ld a,h
    ld (@bmid+1),a
    ld hl,@command
    ld bc,@end-@command
    rst.lil 18h
    ret
@command:
    db 23,0,0A0h
    dw sid
    db 49h,38
@bmid:
    dw 0
@end:

display_expected_bitmap:
    call vdu_clg
    ld hl,(expected_bitmap)
    ld a,l
    ld (@bmid),a
    ld a,h
    ld (@bmid+1),a
    ld hl,@command
    ld bc,@end-@command
    rst.lil 18h
    call vdu_flip
    ret
@command:
    db 23,27,20h
@bmid:
    dw 0
    db 23,27,3
    dw 0,0
@end:

enable_render_notifications:
    ld hl,@command
    ld bc,@end-@command
    rst.lil 18h
    ret
@command:
    db 23,0,0A0h
    dw sid
    db 49h,41,1
    dw render_notify_token
@end:

disable_render_notifications:
    ld hl,@command
    ld bc,@end-@command
    rst.lil 18h
    ret
@command:
    db 23,0,0A0h
    dw sid
    db 49h,41,0
    dw 0
@end:

; MOS calls this from its UART interrupt path with DEU at the payload.
; It only copies state and publishes one-byte flags. No MOS or VDU calls.
render_packet_callback:
    push af
    push ix
    push iy
    push de
    pop ix

    ld a,(ix+0)
    cp 'P'
    jp nz,@keyboard
    ld a,(ix+1)
    cp '3'
    jp nz,@keyboard
    ld a,(ix+2)
    cp 'D'
    jp nz,@keyboard
    ld a,(ix+3)
    cp 'R'
    jp nz,@keyboard

    ld iy,completion_record
    ld a,(ix+0)
    ld (iy+0),a
    ld a,(ix+1)
    ld (iy+1),a
    ld a,(ix+2)
    ld (iy+2),a
    ld a,(ix+3)
    ld (iy+3),a
    ld a,(ix+4)
    ld (iy+4),a
    ld a,(ix+5)
    ld (iy+5),a
    ld a,(ix+6)
    ld (iy+6),a
    ld a,(ix+7)
    ld (iy+7),a
    ld a,(ix+8)
    ld (iy+8),a
    ld a,(ix+9)
    ld (iy+9),a

    ; MOS always resumes normal keyboard handling. Scrub P3DR into a
    ; harmless null key-up event before returning to it.
    xor a
    ld (ix+0),a
    ld (ix+1),a
    ld (ix+2),a
    ld (ix+3),a
    ld a,1
    ld (completion_ready),a
    jr @done

@keyboard:
    ld a,(ix+3)
    cp 1
    jr nz,@done
    ld a,(ix+0)
    cp 27
    jr nz,@done
    ld a,1
    ld (abort_requested),a

@done:
    pop iy
    pop ix
    pop af
    ret

sysvars_pointer: dl 0
world_step_time: dl 0
world_updates: dl 0
world_angle: dl 0
world_step: db 0
world_revision: db 0
submitted_revision: db 0
simulation_done: db 0
render_started: db 0
render_in_flight: db 0
completion_ready: db 0
completion_record: ds 10
completion_snapshot: ds 10
expected_bitmap: dl 0
expected_sequence: ds 2
sequence_initialized: db 0
render_count: db 0
result_code: db 0
abort_requested: db 0

pass_message: db 13,10,"Pingo asynchronous render callback: PASS",13,10,0
timeout_message: db 13,10,"Pingo asynchronous render callback: TIMEOUT",13,10,0
rejected_message: db 13,10,"Pingo asynchronous render callback: RECORD REJECTED",13,10,0
aborted_message: db 13,10,"Pingo asynchronous render callback: ABORTED",13,10,0

filedata:
    ; MOS loads the texture into free RAM beginning at this final label.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "profile",
        nargs="?",
        type=Path,
        default=DEFAULT_PROFILE,
        help="JSON profile (default: benchmarks/render-async/profiles/cube.json)",
    )
    parser.add_argument("--no-assemble", action="store_true")
    args = parser.parse_args()

    profile_path = args.profile
    if not profile_path.is_absolute():
        profile_path = PROJECT_ROOT / profile_path
    profile_path = profile_path.resolve()
    profile = json.loads(profile_path.read_text(encoding="utf-8"))
    profile_source = profile_path.relative_to(PROJECT_ROOT.resolve()).as_posix()
    fixture_name = str(profile["name"])
    if not fixture_name or any(
        character not in "abcdefghijklmnopqrstuvwxyz0123456789-_"
        for character in fixture_name
    ):
        raise ValueError(
            "profile name must contain only lowercase letters, digits, '-' or '_'"
        )
    simulation_steps = int(profile["simulation_steps"])
    simulation_step_ticks = int(profile["simulation_step_ticks"])
    if not 1 <= simulation_steps <= 255:
        raise ValueError("simulation_steps must be between 1 and 255")
    if not 1 <= simulation_step_ticks <= 127:
        raise ValueError("simulation_step_ticks must be between 1 and 127")
    fixture_root = (
        PROJECT_ROOT / "benchmarks" / "render-async" / "fixtures" / fixture_name
    )
    source_dir = fixture_root / "src"
    target_dir = fixture_root / "tgt"
    source_dir.mkdir(parents=True, exist_ok=True)
    target_dir.mkdir(parents=True, exist_ok=True)

    model_source = PROJECT_ROOT / profile["model_source"]
    texture_source = PROJECT_ROOT / profile["texture_source"]
    texture_target = target_dir / profile["texture_filename"]
    shutil.copy2(texture_source, texture_target)
    profile["texture_size"] = texture_target.stat().st_size

    generated_copy(model_source, source_dir / "model.inc", profile_source)
    generated_copy(VDU_HELPERS, source_dir / "vdu_pingo.inc", profile_source)
    source_name = f"async_{fixture_name}.asm"
    (source_dir / source_name).write_text(
        assembly(profile, profile_source),
        encoding="utf-8",
    )

    output = target_dir / f"async_{fixture_name}.bin"
    if not args.no_assemble:
        output.unlink(missing_ok=True)
        subprocess.run(
            ["ez80asm", source_name, f"../tgt/{output.name}"],
            cwd=source_dir,
            check=True,
        )

    print(f"Generated {fixture_root.relative_to(PROJECT_ROOT)}")
    if not args.no_assemble:
        print(f"Assembled {output.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
