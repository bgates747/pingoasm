def parse_arguments() -> argparse.Namespace:
    try:
        separator = sys.argv.index("--")
    except ValueError:
        arguments: list[str] = []
    else:
        arguments = sys.argv[separator + 1 :]
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--mesh-output", type=Path, required=True)
    parser.add_argument("--pose-output", type=Path, required=True)
    parser.add_argument("--metadata-output", type=Path, required=True)
    return parser.parse_args(arguments)


def project_path(value: str) -> Path:
    path = (PROJECT_ROOT / value).resolve()
    path.relative_to(PROJECT_ROOT.resolve())
    return path


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def matrix_error(left: Matrix, right: Matrix) -> float:
    return max(
        abs(left[row][column] - right[row][column])
        for row in range(4)
        for column in range(4)
    )


def round_half_away_from_zero(value: float) -> int:
    """Match the deterministic rounding used by generated Pingo pose data."""

    magnitude = math.floor(abs(value) + 0.5)
    return -magnitude if value < 0.0 else magnitude


def pingo_rotation(angles: tuple[float, float, float]) -> Matrix:
    return (
        Matrix.Rotation(angles[2], 4, "Z")
        @ Matrix.Rotation(angles[1], 4, "Y")
        @ Matrix.Rotation(angles[0], 4, "X")
    )


def encode_mesh_coordinate(value: float) -> int:
    if not math.isfinite(value) or value < -1.000001 or value > 1.000001:
        raise ValueError(f"mesh coordinate outside normalized range: {value!r}")
    result = round_half_away_from_zero(
        max(-1.0, min(1.0, value)) * 32767.0
    )
    if not -32768 <= result <= 32767:
        raise ValueError(f"mesh coordinate outside signed word: {result}")
    return result


def encode_uv_coordinate(value: float) -> int:
    if not math.isfinite(value) or value < -1.0e-5 or value > 1.00001:
        raise ValueError(f"UV coordinate outside normalized range: {value!r}")
    return round_half_away_from_zero(max(0.0, min(1.0, value)) * 65535.0)


def encode_translation(value: float) -> int:
    if not math.isfinite(value):
        raise ValueError(f"non-finite translation: {value!r}")
    result = round_half_away_from_zero(value * 32767.0 / 256.0)
    if not -32768 <= result <= 32767:
        raise ValueError(f"translation outside Pingo signed-word domain: {result}")
    return result


def encode_angle(value: float) -> int:
    if not math.isfinite(value):
        raise ValueError(f"non-finite Euler angle: {value!r}")
    result = round_half_away_from_zero(value * 32767.0 / (2.0 * math.pi))
    if not -32768 <= result <= 32767:
        raise ValueError(f"Euler angle outside Pingo signed-turn domain: {result}")
    return result


