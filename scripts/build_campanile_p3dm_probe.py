#!/usr/bin/env python3
"""Regenerate the landmark corpus and build its isolated Campanile probe."""

from __future__ import annotations

from dataclasses import asdict
from hashlib import sha256
import json
import math
from pathlib import Path
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parent.parent
CANONICAL_OUTPUT = ROOT / "build/p3dm/bay-area-koak-proof"
CANONICAL_INDEX = CANONICAL_OUTPUT / "LANDMARK.json"
FIXTURE = ROOT / "fixtures/campanile-p3dm-probe"
SOURCE = FIXTURE / "src"
TARGET = FIXTURE / "tgt"
GENERATED = SOURCE / "generated/campanile-probe.inc"
COMPONENT_NAME = "CAMPANIL.AGN"
PALETTE_NAME = "SOLID64.RG2"
PROGRAM_NAME = "CAMPTEST.BIN"
P3D_NORM_MAX = 32_767

sys.path.insert(0, str(ROOT / "src"))

from pingo_terrain.adl_width import include_closure  # noqa: E402
from pingo_terrain.p3dm import (  # noqa: E402
    IlluminationPolicy,
    LayerKind,
    MaterialSet,
    ShadingMode,
    make_data,
    parse_container,
)


def file_sha256(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def require_83(name: str) -> None:
    stem, dot, extension = name.partition(".")
    if not stem or len(stem) > 8 or (dot and len(extension) > 3):
        raise ValueError(f"runtime asset is not 8.3-safe: {name}")


def symmetric_round(value: float) -> int:
    return math.floor(value + 0.5) if value >= 0.0 else math.ceil(value - 0.5)


def generated_include(tile) -> tuple[str, dict[str, float | int]]:
    half_extent = tile.meta.model_half_extent_m
    minimum_y = min(position[1] for position in tile.positions)
    maximum_y = max(position[1] for position in tile.positions)
    # Mesh and translation coordinates share /32767 normalization. Object
    # scale turns mesh raw into half_extent metres; translation raw turns into
    # 256 Pingo units = 2,048 metres. The common denominator cancels here.
    translation_y = symmetric_round(-minimum_y * half_extent / 2_048)
    scale_q8_8 = half_extent * 32
    base_residual_m = (
        translation_y * 2_048 / P3D_NORM_MAX
        + minimum_y * half_extent / P3D_NORM_MAX
    )
    top_m = (
        translation_y * 2_048 / P3D_NORM_MAX
        + maximum_y * half_extent / P3D_NORM_MAX
    )
    values = {
        "model_half_extent_m": half_extent,
        "scale_q8_8": scale_q8_8,
        "translation_y": translation_y,
        "minimum_encoded_y": minimum_y,
        "maximum_encoded_y": maximum_y,
        "base_residual_m": base_residual_m,
        "decoded_top_m": top_m,
    }
    source = (
        "; Generated by scripts/build_campanile_p3dm_probe.py.\n"
        "; Do not hand-edit; values witness the freshly regenerated corpus.\n"
        f"campanile_tile_x: equ {tile.meta.tile_x}\n"
        f"campanile_tile_y: equ {tile.meta.tile_y}\n"
        f"campanile_model_half_extent_m: equ {half_extent}\n"
        f"campanile_scale_q8_8: equ {scale_q8_8}\n"
        f"campanile_local_translation_y: equ {translation_y}\n"
        f"campanile_vertex_count: equ {len(tile.positions)}\n"
        f"campanile_position_index_count: equ {len(tile.position_indices)}\n"
    )
    return source, values


def normalized_meta(tile) -> dict[str, int]:
    meta = asdict(tile.meta)
    for field in (
        "layer_kind",
        "shading_mode",
        "illumination",
        "material_set",
    ):
        meta[field] = int(meta[field])
    return meta


def main() -> int:
    for name in (COMPONENT_NAME, PALETTE_NAME, PROGRAM_NAME):
        require_83(name)

    # This is intentionally first: the probe never consumes a stale landmark
    # copied by an earlier run and automatically follows corpus corrections.
    subprocess.run(
        [sys.executable, str(ROOT / "scripts/build_landmark_p3dm.py")],
        cwd=ROOT,
        check=True,
    )
    canonical = json.loads(CANONICAL_INDEX.read_text(encoding="utf-8"))
    record = next(
        item for item in canonical["landmarks"] if item["id"] == "campanile"
    )
    canonical_component = CANONICAL_OUTPUT / record["component"]["path"]
    canonical_palette = CANONICAL_OUTPUT / canonical["solid_selector_palette"]["path"]
    tile = parse_container(canonical_component.read_bytes())
    expected_policy = (
        LayerKind.LANDMARK,
        ShadingMode.SOLID_FLAT,
        IlluminationPolicy.SCENE,
        MaterialSet.NATIVE_SOLID_PALETTE,
    )
    actual_policy = (
        tile.meta.layer_kind,
        tile.meta.shading_mode,
        tile.meta.illumination,
        tile.meta.material_set,
    )
    if actual_policy != expected_policy:
        raise SystemExit(f"Campanile render policy changed: {actual_policy}")

    data = make_data(tile)
    component_witness = {
        "bytes": canonical_component.stat().st_size,
        "sha256": file_sha256(canonical_component),
        "data_bytes": len(data),
        "data_sha256": sha256(data).hexdigest(),
        "vertices": len(tile.positions),
        "triangles": len(tile.position_indices) // 3,
        "meta": normalized_meta(tile),
    }
    for field, actual in component_witness.items():
        expected = record["component"][field]
        if actual != expected:
            raise SystemExit(
                f"fresh Campanile component disagrees with index {field}: "
                f"expected {expected!r}, got {actual!r}"
            )
    palette_witness = canonical["solid_selector_palette"]
    if canonical_palette.stat().st_size != palette_witness["bytes"]:
        raise SystemExit("fresh landmark palette byte count disagrees with index")
    if file_sha256(canonical_palette) != palette_witness["sha256"]:
        raise SystemExit("fresh landmark palette hash disagrees with index")

    TARGET.mkdir(parents=True, exist_ok=True)
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(canonical_component, TARGET / COMPONENT_NAME)
    shutil.copy2(canonical_palette, TARGET / PALETTE_NAME)
    include_source, placement = generated_include(tile)
    GENERATED.write_text(include_source, encoding="ascii")

    main_source = SOURCE / "campanile-p3dm-probe.asm"
    audit = subprocess.run(
        [
            sys.executable,
            str(ROOT / "scripts/audit_adl_width.py"),
            "--follow-includes",
            "--fail-review",
            str(main_source),
        ],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    output = TARGET / PROGRAM_NAME
    subprocess.run(
        ["ez80asm", main_source.name, f"../tgt/{PROGRAM_NAME}"],
        cwd=SOURCE,
        check=True,
    )

    closure = include_closure([main_source])
    manifest = {
        "schema": "pingo-terrain-campanile-p3dm-probe-v1",
        "canonical_landmark_index": {
            "path": str(CANONICAL_INDEX.relative_to(ROOT)),
            "sha256": file_sha256(CANONICAL_INDEX),
            "build_signature_sha256": canonical["build_signature_sha256"],
        },
        "component": {
            "source_path": record["component"]["path"],
            "runtime_name": COMPONENT_NAME,
            "bytes": (TARGET / COMPONENT_NAME).stat().st_size,
            "sha256": file_sha256(TARGET / COMPONENT_NAME),
            "data_bytes": len(data),
            "data_sha256": sha256(data).hexdigest(),
            "vertices": len(tile.positions),
            "position_indices": len(tile.position_indices),
            "triangles": len(tile.position_indices) // 3,
            "uvs": len(tile.uvs),
            "uv_indices": len(tile.uv_indices),
            "meta": normalized_meta(tile),
        },
        "palette": {
            "runtime_name": PALETTE_NAME,
            "dimensions": [8, 8],
            "bytes": (TARGET / PALETTE_NAME).stat().st_size,
            "sha256": file_sha256(TARGET / PALETTE_NAME),
            "selectors": record["component"]["selectors"],
            "policy": "native solid-flat selector palette; no dither or imagery",
        },
        "local_placement": {
            **placement,
            "translation_x": 0,
            "translation_z": 0,
            "preserves_component_scale_and_mesh": True,
        },
        "camera": {
            "position_translation_counts": [-2304, 1152, 2304],
            "target_translation_counts": [0, 720, 0],
            "counts_per_metre": 16,
            "orientation": "integer p3d upright look-at",
        },
        "lighting": {
            "direction": [-16384, 16384, -16384],
            "ambient_of_127": 72,
        },
        "assembly": {
            "program_runtime_name": PROGRAM_NAME,
            "bytes": output.stat().st_size,
            "sha256": file_sha256(output),
            "adl_audit": audit.stdout.strip(),
            "include_closure": [
                {
                    "path": str(path.relative_to(ROOT)),
                    "sha256": file_sha256(path),
                }
                for path in closure
            ],
        },
    }
    manifest_path = TARGET / "probe.json"
    manifest_path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(
        "CAMPANILE_P3DM_PROBE",
        f"component_sha256={manifest['component']['sha256']}",
        f"vertices={manifest['component']['vertices']}",
        f"triangles={manifest['component']['triangles']}",
        f"base_residual_m={placement['base_residual_m']:.9f}",
        f"binary_sha256={manifest['assembly']['sha256']}",
        f"output={output}",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
