#!/usr/bin/env python3
"""Exhaustively audit encoded regular-LOD recipes at every corpus origin.

This is intentionally a release/audit command rather than a default unit
test. It decodes the generated byte ABI, applies clipped source ordinals at
all valid directed neighbor crossings, proves every intermediate stage fits
the 255-slot manager, and proves exact final ownership.
"""

from __future__ import annotations

from functools import lru_cache
import hashlib
import json
import time

from pingo_terrain.hex_terrain import HEX_Q_MAX, disk_offsets, rows_for_q
from pingo_terrain.regular_lod import HIERARCHY_LEVEL_BY_LOD, offset_row
from pingo_terrain.regular_lod_runtime import (
    MANAGER_SLOT_COUNT,
    PHASE_OFFSET_ROW_COUNT,
    PHASE_Q_COUNT,
    TRANSITION_DIRECTION_STEPS,
    TRANSITION_RECIPE_COUNT,
    build_phase_plan,
    decode_transition_recipe,
    encode_transition_table,
)


EXPECTED_REPORT = {
    "origins": 50_183,
    "valid_directed_transitions": 299_306,
    "nonempty_filtered_groups": 6_146_608,
    "endpoint_owner_range": [61, 250],
    "maximum_retiring_group": 14,
    "maximum_entering_group": 14,
    "maximum_group_total": 15,
    "minimum_staging_margin": 4,
    "provider_reordered_groups": 347_569,
    "table_bytes": 21_504,
    "table_sha256": (
        "34fd0c448e6b653d4ab25883eb283a328dc5825cd6232591866059cbd2b6a79d"
    ),
}


def verify_report(report: dict[str, object]) -> None:
    """Reject any semantic witness drift while ignoring elapsed wall time."""

    mismatches = {
        key: (report.get(key), expected)
        for key, expected in EXPECTED_REPORT.items()
        if report.get(key) != expected
    }
    elapsed = report.get("elapsed_seconds")
    if not isinstance(elapsed, (int, float)) or elapsed < 0:
        mismatches["elapsed_seconds"] = (elapsed, "a nonnegative number")
    if mismatches:
        raise RuntimeError(f"regular-LOD transition audit changed: {mismatches}")


def _valid_cell(q: int, r: int) -> bool:
    if not 0 <= q <= HEX_Q_MAX:
        return False
    row = r + q // 2
    return 0 <= row < rows_for_q(q)


def _coarse_present(lod: int, anchor_q: int, anchor_row: int) -> bool:
    """Return whether an aligned hierarchy node owns any bounded L0 cell."""

    level = HIERARCHY_LEVEL_BY_LOD[lod]
    first_q = max(0, anchor_q)
    final_q = min(HEX_Q_MAX + 1, anchor_q + level.width_q)
    if first_q >= final_q:
        return False
    final_row = anchor_row + level.height_rows
    return any(
        max(0, anchor_row) < min(rows_for_q(q), final_row)
        for q in range(first_q, final_q)
    )


@lru_cache(maxsize=4096)
def _source_owners(q: int, r: int) -> tuple[tuple | None, ...]:
    """Return the unbounded ordinal domain with None for clipped owners."""

    row = offset_row(q, r)
    owners: list[tuple | None] = []
    for delta_q, delta_r in disk_offsets(5):
        owner_q = q + delta_q
        owner_r = r + delta_r
        owners.append(
            (0, owner_q, owner_r)
            if _valid_cell(owner_q, owner_r)
            else None
        )
    phase = build_phase_plan(
        5,
        q % PHASE_Q_COUNT,
        row % PHASE_OFFSET_ROW_COUNT,
    )
    for entry in phase.entries:
        anchor_q = q + entry.anchor_q_offset
        anchor_row = row + entry.anchor_offset_row_offset
        owners.append(
            (1, entry.lod, anchor_q, anchor_row)
            if _coarse_present(entry.lod, anchor_q, anchor_row)
            else None
        )
    return tuple(owners)


def audit_transition_recipes() -> dict[str, object]:
    """Run and return the complete encoded-byte corpus witness."""

    started = time.monotonic()
    encoded = encode_transition_table()
    offsets = tuple(
        int.from_bytes(encoded[index * 3 : index * 3 + 3], "little")
        for index in range(TRANSITION_RECIPE_COUNT)
    )
    recipes = []
    for index, start in enumerate(offsets):
        end = offsets[index + 1] if index + 1 < len(offsets) else len(encoded)
        recipes.append(decode_transition_recipe(encoded[start:end]))

    origins = 0
    transitions = 0
    groups = 0
    maximum_retiring = 0
    maximum_entering = 0
    maximum_group_total = 0
    minimum_margin = MANAGER_SLOT_COUNT
    maximum_endpoint = 0
    minimum_endpoint = MANAGER_SLOT_COUNT
    provider_reordered_groups = 0

    for q in range(HEX_Q_MAX + 1):
        for row in range(rows_for_q(q)):
            r = row - q // 2
            old_map = _source_owners(q, r)
            old_present = tuple(owner for owner in old_map if owner is not None)
            if len(set(old_present)) != len(old_present):
                raise AssertionError(("duplicate old owner", q, r))
            origins += 1
            for direction, (delta_q, delta_r) in enumerate(
                TRANSITION_DIRECTION_STEPS
            ):
                new_q = q + delta_q
                new_r = r + delta_r
                if not _valid_cell(new_q, new_r):
                    continue
                new_map = _source_owners(new_q, new_r)
                new_present = tuple(
                    owner for owner in new_map if owner is not None
                )
                if len(set(new_present)) != len(new_present):
                    raise AssertionError(("duplicate new owner", q, r, direction))
                recipe_index = ((q & 7) * 4 + (row & 3)) * 6 + direction
                active = set(old_present)
                minimum_endpoint = min(
                    minimum_endpoint,
                    len(old_present),
                    len(new_present),
                )
                maximum_endpoint = max(
                    maximum_endpoint,
                    len(old_present),
                    len(new_present),
                )
                pending = []
                for source_index, ordinal_group in enumerate(recipes[recipe_index]):
                    retiring = tuple(
                        old_map[ordinal]
                        for ordinal in ordinal_group.retiring_ordinals
                        if old_map[ordinal] is not None
                    )
                    entering = tuple(
                        new_map[ordinal]
                        for ordinal in ordinal_group.entering_ordinals
                        if new_map[ordinal] is not None
                    )
                    retiring_set = set(retiring)
                    entering_set = set(entering)
                    if len(retiring_set) != len(retiring):
                        raise AssertionError(("duplicate retiring", q, r, direction))
                    if len(entering_set) != len(entering):
                        raise AssertionError(("duplicate entering", q, r, direction))
                    pending.append(
                        (source_index, retiring_set, entering_set)
                    )

                while pending:
                    free = MANAGER_SLOT_COUNT - len(active)
                    feasible = [
                        group
                        for group in pending
                        if len(group[2]) <= free
                    ]
                    if not feasible:
                        raise AssertionError(
                            ("provider selection dead end", q, r, direction, free)
                        )
                    selected = max(
                        feasible,
                        key=lambda group: (
                            len(group[1]) - len(group[2]),
                            -len(group[2]),
                            len(group[1]),
                            -group[0],
                        ),
                    )
                    if selected is not pending[0]:
                        provider_reordered_groups += 1
                    pending.remove(selected)
                    _source_index, retiring_set, entering_set = selected
                    if not retiring_set <= active:
                        raise AssertionError(("retiring not active", q, r, direction))
                    if not entering_set.isdisjoint(active):
                        raise AssertionError(("entering already active", q, r, direction))
                    staging_margin = MANAGER_SLOT_COUNT - len(active) - len(
                        entering_set
                    )
                    if staging_margin < 0:
                        raise AssertionError(
                            ("slot overflow", q, r, direction, staging_margin)
                        )
                    minimum_margin = min(minimum_margin, staging_margin)
                    maximum_retiring = max(maximum_retiring, len(retiring_set))
                    maximum_entering = max(maximum_entering, len(entering_set))
                    maximum_group_total = max(
                        maximum_group_total,
                        len(retiring_set) + len(entering_set),
                    )
                    active.difference_update(retiring_set)
                    active.update(entering_set)
                    groups += bool(retiring_set or entering_set)
                target = set(new_present)
                if active != target:
                    raise AssertionError(
                        (
                            "wrong target",
                            q,
                            r,
                            direction,
                            len(active ^ target),
                        )
                    )
                transitions += 1

    return {
        "origins": origins,
        "valid_directed_transitions": transitions,
        "nonempty_filtered_groups": groups,
        "endpoint_owner_range": [minimum_endpoint, maximum_endpoint],
        "maximum_retiring_group": maximum_retiring,
        "maximum_entering_group": maximum_entering,
        "maximum_group_total": maximum_group_total,
        "minimum_staging_margin": minimum_margin,
        "provider_reordered_groups": provider_reordered_groups,
        "table_bytes": len(encoded),
        "table_sha256": hashlib.sha256(encoded).hexdigest(),
        "elapsed_seconds": round(time.monotonic() - started, 3),
    }


def main() -> None:
    report = audit_transition_recipes()
    verify_report(report)
    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
