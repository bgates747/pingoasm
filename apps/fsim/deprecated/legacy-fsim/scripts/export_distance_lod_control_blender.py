#!/usr/bin/env python3
"""Export the first ring-30 coarse-distance control from the regular review.

Run through Blender so the accepted review mesh supplies its projected vertex,
elevation, cell-owner, and semantic-material attributes::

    blender --background --python scripts/export_distance_lod_control_blender.py

The natural runtime corpus is not modified.  This script emits only the
middle/far annulus used by the sibling mixed-LOD experiment.
"""

from __future__ import annotations

import argparse
from array import array
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import shutil
import sys
from typing import Sequence


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "build/visualization/bay-area-hex-overview.blend"
SOURCE_SHA256 = "3cc3d95e1b41655594eb1002ad6de61a3bac7d102a964f6f3e1c9983150f12ea"
SOURCE_OBJECT = "Bay Area — complete hex terrain corpus"
OUTPUT = ROOT / "build/p3dm/bay-area-distance-lod-control"
NEAR_RESOURCES = ROOT / "build/p3dm/bay-area-natural-full-l0"
PLAN_SCHEMA = "pingo-terrain-distance-lod-control-v1"

sys.path.insert(0, str(ROOT / "src"))

from pingo_terrain.distance_lod import (  # noqa: E402
    FAR_RING,
    MESH_ID_BASE,
    MODEL_HALF_EXTENT_M,
    NEAR_RING,
    NEAR_SLOT_COUNT,
    OBJECT_ID_BASE,
    OBJECT_SCALE_Q8_8,
    P3DM_FILE_LIMIT,
    START_CELL,
    DistanceFace,
    DistanceVertex,
    build_chunk,
    chunk_key,
)
from pingo_terrain.p3dm import make_container, parse_container  # noqa: E402


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def arguments(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    return parser.parse_args(argv)


def _attribute_values(mesh, name: str, code: str) -> array:
    attribute = mesh.attributes.get(name)
    if attribute is None:
        raise SystemExit(f"regular review omitted required attribute {name!r}")
    values = array(code, [0]) * len(attribute.data)
    attribute.data.foreach_get("value", values)
    return values


def _atomic_bytes(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_bytes(payload)
    temporary.replace(path)


def _assembly_include(chunks) -> str:
    lines = [
        "; AUTO-GENERATED by scripts/export_distance_lod_control_blender.py",
        f"distance_lod_chunk_count: equ {len(chunks)}",
        f"distance_lod_mesh_id_base: equ {MESH_ID_BASE}",
        f"distance_lod_object_id_base: equ {OBJECT_ID_BASE}",
        f"distance_lod_near_slot_count: equ {NEAR_SLOT_COUNT}",
        f"distance_lod_object_scale_q8_8: equ {OBJECT_SCALE_Q8_8}",
        "distance_lod_record_bytes: equ 14",
        "distance_lod_record_lod: equ 0",
        "distance_lod_record_tile_x: equ 1",
        "distance_lod_record_tile_y: equ 3",
        "distance_lod_record_translation_x: equ 5",
        "distance_lod_record_translation_y: equ 8",
        "distance_lod_record_translation_z: equ 11",
        "distance_lod_records:",
    ]
    for chunk in chunks:
        x, y, z = chunk.translation_counts
        lines.extend(
            (
                f"    db {chunk.tier}",
                f"    dw {chunk.bucket_q},{chunk.bucket_r}",
                f"    dl {x},{y},{z}",
            )
        )
    lines.append("distance_lod_records_end:")
    return "\n".join(lines) + "\n"


def export(bpy, source: Path, output: Path) -> dict:
    source = source.expanduser().resolve()
    output = output.expanduser().resolve()
    if sha256(source) != SOURCE_SHA256:
        raise SystemExit(f"regular review source changed: {source}")
    if not bpy.data.filepath or Path(bpy.data.filepath).resolve() != source:
        bpy.ops.wm.open_mainfile(filepath=str(source))
    scene = bpy.context.scene
    if scene.get("artifact_schema") != "pingo-terrain-blender-review-v1":
        raise SystemExit("regular review schema changed")
    if scene.get("preview_lod") != "one-centre-six-triangle-per-cell":
        raise SystemExit("regular review is no longer the six-triangle control")
    terrain = bpy.data.objects.get(SOURCE_OBJECT)
    if terrain is None or terrain.type != "MESH":
        raise SystemExit("regular review terrain object is missing")
    mesh = terrain.data
    if len(mesh.vertices) != 151_446 or len(mesh.polygons) != 301_098:
        raise SystemExit("regular review topology count changed")
    if any(len(polygon.vertices) != 3 for polygon in mesh.polygons):
        raise SystemExit("regular review contains a non-triangle")

    east = _attribute_values(mesh, "utm_easting_m", "i")
    north = _attribute_values(mesh, "utm_northing_m", "i")
    elevation = _attribute_values(mesh, "elevation_navd88_m", "f")
    q_values = _attribute_values(mesh, "hex_q", "i")
    r_values = _attribute_values(mesh, "hex_r", "i")
    materials = _attribute_values(mesh, "terrain_material_id", "i")
    polygon_vertices = array("i", [0]) * (3 * len(mesh.polygons))
    mesh.polygons.foreach_get("vertices", polygon_vertices)

    grouped: dict[tuple[int, int, int], list[DistanceFace]] = defaultdict(list)
    selected_vertices: set[int] = set()
    cell_faces: Counter[tuple[int, int]] = Counter()
    for face_index, (q, r, material) in enumerate(
        zip(q_values, r_values, materials, strict=True)
    ):
        start = face_index * 3
        face = DistanceFace(
            tuple(polygon_vertices[start : start + 3]),
            int(q),
            int(r),
            int(material),
        )
        key = chunk_key(face)
        if key is None:
            continue
        grouped[key].append(face)
        selected_vertices.update(face.vertices)
        cell_faces[(face.q, face.r)] += 1

    expected_cells = 1 + 3 * FAR_RING * (FAR_RING + 1) - (
        1 + 3 * NEAR_RING * (NEAR_RING + 1)
    )
    if len(cell_faces) != expected_cells or set(cell_faces.values()) != {6}:
        raise SystemExit("regular review did not yield six faces for every annulus cell")
    if sum(cell_faces.values()) != 16_200:
        raise SystemExit("distance annulus triangle count changed")

    vertex_map = {
        index: DistanceVertex(int(east[index]), int(north[index]), float(elevation[index]))
        for index in sorted(selected_vertices)
    }
    chunks = tuple(
        build_chunk(ordinal, key, grouped[key], vertex_map)
        for ordinal, key in enumerate(sorted(grouped))
    )
    if not 1 <= len(chunks) or NEAR_SLOT_COUNT + len(chunks) > 255:
        raise SystemExit(
            "combined natural/distance slot count no longer fits the u8 manager"
        )

    records = []
    for chunk in chunks:
        container = make_container(chunk.tile)
        if len(container) > P3DM_FILE_LIMIT:
            raise SystemExit(
                f"distance record {chunk.ordinal} exceeds {P3DM_FILE_LIMIT} bytes"
            )
        if parse_container(container) != chunk.tile:
            raise AssertionError("distance record changed during P3DM round trip")
        path = output / chunk.relative_path
        _atomic_bytes(path, container)
        records.append(
            {
                "ordinal": chunk.ordinal,
                "tier": chunk.tier,
                "bucket_q": chunk.bucket_q,
                "bucket_r": chunk.bucket_r,
                "cells": [list(cell) for cell in chunk.cells],
                "path": chunk.relative_path.as_posix(),
                "bytes": len(container),
                "sha256": hashlib.sha256(container).hexdigest(),
                "vertices": len(chunk.tile.positions),
                "surface_triangles": chunk.surface_triangles,
                "skirt_triangles": chunk.skirt_triangles,
                "translation_counts": list(chunk.translation_counts),
                "tile_x": chunk.tile.meta.tile_x,
                "tile_y": chunk.tile.meta.tile_y,
                "lod": chunk.tile.meta.lod,
            }
        )

    include = _assembly_include(chunks)
    _atomic_bytes(output / "DISTLOD.INC", include.encode("ascii"))
    for name in ("MATID.RG2", "PATTERN.RG2", "PATLUT.BIN"):
        shutil.copy2(NEAR_RESOURCES / name, output / name)
    report = {
        "schema": PLAN_SCHEMA,
        "source": {
            "path": str(source.relative_to(ROOT)),
            "sha256": SOURCE_SHA256,
            "object": SOURCE_OBJECT,
            "preview_lod": scene["preview_lod"],
        },
        "origin_cell": list(START_CELL),
        "rings": {"near": [0, 5], "middle": [6, 15], "far": [16, 30]},
        "geometry": {
            "selected_cells": len(cell_faces),
            "surface_triangles": sum(chunk.surface_triangles for chunk in chunks),
            "skirt_triangles": sum(chunk.skirt_triangles for chunk in chunks),
            "chunks": len(chunks),
            "model_half_extent_m": MODEL_HALF_EXTENT_M,
            "object_scale_q8_8": OBJECT_SCALE_Q8_8,
            "maximum_record_bytes": max(record["bytes"] for record in records),
            "container_bytes": sum(record["bytes"] for record in records),
        },
        "runtime": {
            "mesh_id_base": MESH_ID_BASE,
            "object_id_base": OBJECT_ID_BASE,
            "path": "DST/HH/LL.AGN",
            "static_origin_proof": True,
            "transition_policy": "honest nonconforming join plus 64 m chunk skirts",
        },
        "records": records,
    }
    payload = (json.dumps(report, indent=2, sort_keys=True) + "\n").encode("utf-8")
    _atomic_bytes(output / "DISTANCE.json", payload)
    return report


def main(argv: Sequence[str] | None = None) -> int:
    args = arguments(argv)
    try:
        import bpy
    except ImportError as error:  # pragma: no cover - Blender owns this path
        raise SystemExit("run this exporter through Blender") from error
    report = export(bpy, args.source, args.output)
    print(
        "DISTANCE_LOD_EXPORT",
        f"chunks={report['geometry']['chunks']}",
        f"triangles={report['geometry']['surface_triangles']}",
        f"bytes={report['geometry']['container_bytes']}",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []))
